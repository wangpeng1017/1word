async function updateSentences() {
    console.log('开始更新填空题例句...\n')

    let updated = 0
    let notFound = 0
    let errors = 0

    for (const [word, sentence] of Object.entries(sentences)) {
        try {
            const vocab = await prisma.vocabularies.findFirst({
                where: { word: word }
            })

            if (!vocab) {
                notFound++
                console.log(`⚠️  ${word}: 未找到单词`)
                continue
            }

            const result = await prisma.questions.updateMany({
                where: {
                    vocabularyId: vocab.id,
                    type: 'FILL_IN_BLANK',
                    OR: [
                        { sentence: null },
                        { sentence: '' }
                    ]
                },
                data: {
                    content: sentence,
                    sentence: sentence
                }
            })

            if (result.count > 0) {
                updated++
                console.log(`✓ ${word}`)
            } else {
                notFound++
                console.log(`⚠️  ${word}: 未找到对应题目或已有例句`)
            }
        } catch (error) {
            errors++
            console.error(`❌ ${word}: ${error.message}`)
        }
    }

    console.log(`\n完成！`)
    console.log(`- 成功更新: ${updated}`)
    console.log(`- 未找到: ${notFound}`)
    console.log(`- 错误: ${errors}`)
}

updateSentences()
    .catch(console.error)
    .finally(() => prisma.$disconnect())
